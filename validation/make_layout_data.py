"""Generate lean/SmcTamper/Layout/LayoutData.lean from validation/layout/{dyn_x64,tp_x64}.json (deterministic).
The data are evidence (what AsmJit and MASM emitted); the Lean theorems compare them with the Lean encodings."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
dyn = json.loads((ROOT / "validation/layout/dyn_x64.json").read_text())
tp = json.loads((ROOT / "validation/layout/tp_x64.json").read_text())
NL = "\n"


def blob(name, doc, bs):
    n = sum(b << (8 * i) for i, b in enumerate(bs))
    return (f"/-- {doc} Little-endian: byte `i` is `(n >>> (8 * i)) % 256`. -/" + NL +
            f"def {name} : Nat := 0x{n:x}" + NL + NL)


out = "module" + NL + NL + "@[expose] public section" + NL + NL + "namespace SmcTamper" + NL + NL
out += "/-! Generated by `validation/make_layout_data.py`; do not edit. Evidence data (M-class), compared in `Layout/Compare`. -/" + NL + NL
out += blob("dynBlob", f"The {dyn['size']} bytes AsmJit emitted for `gen_asm` ({dyn['printed']['line']}).", dyn["bytes"])
out += blob("tpCompLoopObjBlob", f"The {len(tp['tpcomploop'])} bytes of `TPCompLoop` in the MASM object of `TP.asm`, REL32 relocations resolved.", tp["tpcomploop"])
out += blob("tpCompObjBlob", f"The {len(tp['tpcomp'])} bytes of `TPComp` in the MASM object of `TP.asm`.", tp["tpcomp"])
out += "end SmcTamper" + NL
(ROOT / "lean/SmcTamper/Layout/LayoutData.lean").write_text(out, encoding="utf-8", newline="\n")
print("wrote", len(out))
