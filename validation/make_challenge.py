"""Generate lean/Challenge.lean mechanically from the Spec modules (plan D6).

The Challenge is the Spec modules reachable from SmcTamper.Spec.Paper, concatenated in import order, with imports and
`theorem` blocks removed and every declaration that the selected statements do not (transitively) mention pruned, and a single
theorem `PalomarSMT.mathematical_result` whose proof is `sorry`.
Usage: python validation/make_challenge.py [--check]   (--check fails when lean/Challenge.lean differs)."""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
TOP = "SmcTamper.Spec.Paper"
ROOTS = ["SecurityTheorem", "AssumptionsNecessary", "MediationTheorem", "LevelMatrix"]
HEADER = '''module
public section
/-!
# Tamper-proofing with self-modifying code: selected mathematical result
Morse and Kozsik, *Tamper-Proofing with Self-Modifying Code*, arXiv:2604.12407, with the corrections recorded in
lean/errata. The statement selects the threat-model results: security of SMC checksumming units under the structural
assumptions A1-A8 and the cost contract (T1), the mediation cost of split views (T2), the necessity of every assumption
(T3) and the level matrix (T4). Definitions keep the
development's names. The x86-64 model, the kernels, the layout and the timing contract are outside this statement; see
PALOMAR_SEMANTICS.md. This file is generated by validation/make_challenge.py from lean/SmcTamper/Spec/*.lean.
The single intentional theorem hole belongs to Challenge; Solution proves it. No custom axiom is assumed.
AI-assisted development; no independent human review is claimed. Not registered.
-/
'''
FOOTER = '''namespace PalomarSMT
/-- Security under A1-A8, mediation cost, necessity of the assumptions, and the level matrix. -/
theorem mathematical_result : SmcTamper.Paper.SecurityTheorem ∧ SmcTamper.Paper.AssumptionsNecessary ∧
    SmcTamper.Paper.MediationTheorem ∧ SmcTamper.Paper.LevelMatrix := by
  sorry
end PalomarSMT
'''
START = re.compile(r"^(/--|/-!|@\[|def\b|noncomputable def\b|structure\b|inductive\b|abbrev\b|theorem\b|lemma\b|instance\b|"
                   r"set_option\b|open\b|variable\b|private\b)")
KW = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?(def|structure|inductive|abbrev|theorem|lemma|instance)\s+([\w.']+)")


def path(m): return LEAN / (m.replace(".", "/") + ".lean")


def imports(m): return re.findall(r"^public import\s+(SmcTamper[\w.]*)", path(m).read_text(encoding="utf-8"), re.M)


def order(m, seen, out):
    if m in seen: return
    seen.add(m)
    for i in imports(m): order(i, seen, out)
    out.append(m)


def chunks(m):
    """(module-level text, [chunk]) : chunk = (defined name or None, kind, text). Namespace lines are kept as structure."""
    text = path(m).read_text(encoding="utf-8").replace("\r\n", "\n").split("public section", 1)[1]
    lines = text.strip("\n").split("\n")
    out, cur = [], []
    for ln in lines:
        top = START.match(ln) or re.match(r"^(namespace|end)\b", ln)
        if top and not (cur and cur[-1].lstrip().startswith("/--") and not cur[-1].rstrip().endswith("-/") and False):
            # a docstring line directly above a declaration belongs to it
            if cur and re.match(r"^(def|structure|inductive|abbrev|theorem|lemma|instance|@\[|noncomputable)", ln) and \
                    "".join(cur).strip().startswith("/--") and "".join(cur).rstrip().endswith("-/"):
                cur.append(ln); continue
            if cur: out.append(cur)
            cur = [ln]
        else:
            cur.append(ln)
    if cur: out.append(cur)
    res = []
    for c in out:
        body = "\n".join(c).rstrip("\n")
        stripped = re.sub(r"^/--.*?-/\s*", "", body, flags=re.S) if body.lstrip().startswith("/--") else body
        mm = KW.match(stripped)
        kind = mm.group(1) if mm else ("ns" if re.match(r"^(namespace|end)\b", stripped) else "other")
        res.append((mm.group(2) if mm else None, kind, body))
    return res


def words(s):
    return set(re.findall(r"[A-Za-z_][\w']*", s))


def HEADER_STRIPPED(t):
    return t.replace(HEADER, '')


def build():
    mods = []; order(TOP, set(), mods)
    per = {}
    allc = []
    for m in mods:
        for (n, k, b) in chunks(m):
            if k in ("theorem", "lemma"): continue
            allc.append([m, n, k, b])
    defs = {}
    for idx, (m, n, k, b) in enumerate(allc):
        if n:
            for part in set(n.split(".")): defs.setdefault(part, []).append(idx)
    keep = set(); work = []
    for r in ROOTS:
        for idx in defs.get(r, []):
            if allc[idx][0] == TOP and idx not in keep: keep.add(idx); work.append(idx)
    while work:
        idx = work.pop()
        for w in words(allc[idx][3]):
            for j in defs.get(w, []):
                if j not in keep: keep.add(j); work.append(j)
    parts = [HEADER]
    for m in mods:
        mine = [(i, c) for i, c in enumerate(allc) if c[0] == m]
        body = [c for i, c in mine if i in keep]
        if not body: continue
        ns = [c[3] for i, c in mine if c[2] == "ns" and c[3].startswith("namespace")]
        ends = [c[3] for i, c in mine if c[2] == "ns" and c[3].startswith("end")]
        parts.append(f"-- ===== {m} =====")
        parts += ns
        parts.append("")
        for c in body:
            # unrelated "other" chunks (module docs, opens, set_option) kept only when they are set_option/open
            parts.append(c[3] + "\n")
        parts += ends
    parts.append(FOOTER)
    out = "\n".join(parts)
    m = re.search(r".{0,40}\b(axiom|native_decide|unsafe|implemented_by)\b.{0,40}", out.replace(HEADER, ""))
    assert not m, "forbidden token in Challenge: " + m.group(0)
    return out


if __name__ == "__main__":
    new = build(); out = LEAN / "Challenge.lean"
    if "--check" in sys.argv:
        old = out.read_text(encoding="utf-8") if out.exists() else ""
        if old.replace("\r\n", "\n") != new: print("Challenge.lean is out of date"); sys.exit(1)
        print("Challenge.lean up to date"); sys.exit(0)
    out.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote {out}: {new.count(chr(10))} lines, {len(new.encode('utf-8'))} bytes")
